// Background scenery — hills, bushes, clouds, castles, bridges, fences,
// the far and near mountain ranges, tree foliage, seaweed and the animated water line.
// Everything here is authored as string-row pixel data: '.' is transparent,
// '0'-'9'/'a'-'f' index the module palette. Light always falls from the upper left.
//
// TONE POLICY. The hills are deliberately FOUR tones — outline, shadow, mid, lit —
// with hard terraced band edges 20/22/24 px wide, because an eight-tone airbrushed
// gradient reads as CG and not as a Super Mario Bros. landform. The mountains are
// likewise flat: two ridge layers, two tones each plus a crest line, no snow caps
// and not one dithered pixel. Rounded volumes (clouds, bushes, canopy) still get
// the full ramp; landforms do not.
//
// ANIMATION POLICY. Nothing here is static and nothing here is a frame slid
// sideways. WATER_LINE composites both of its crests from one kit at FIXED columns
// and animates only their height, so a crest cannot teleport; SEAWEED cantilevers
// from a rock that is byte-identical in all five frames; TREE.rustle deforms the
// canopy — B lifts a row and thickens its widest band, C deletes an interior row
// and bulges the skirt — while trunk rows 24-31 stay byte-identical in all three,
// so the joint with TREE.trunk never jitters. Every frame of every cycle differs
// from every other frame of that cycle by a wide margin; none is a translation or
// a column rotation of another.
//
// PALETTE POLICY. Materials that share a scene are kept at least 40 RGB units
// apart: water against cloud and mountain, bridge timber against fence, seaweed
// against land foliage, flag linen against timber. Ramps that used to be one
// another with rounding noise are now genuinely different hues.
//
// Anything that gets stamped repeatedly ships a second wear pattern: FENCE.alt,
// BRIDGE.plank / .plankB, TREE.trunkB and WATER_LINE.waveB. Alternate them along a
// run and the fence, the span, the trunk and the shoreline read as surfaces instead
// of one tile printed forty times.
