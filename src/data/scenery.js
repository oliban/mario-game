// Background scenery — hills, bushes, clouds, castles, bridges, fences,
// the far and near mountain ranges, tree foliage, seaweed and the animated water line.
// Everything here is authored as string-row pixel data: '.' is transparent,
// '0'-'9'/'a'-'f' index the module palette. Light always falls from the upper left:
// every rounded form is shaded as a hemisphere, so the terminator is a curved arc
// sweeping down-right, never a vertical stripe.
//
// Nothing in this module is static. Water, seaweed, tree canopy, the flagpole
// cloth and the clouds all cycle, and every cycle DEFORMS its subject — crests
// change height, blades cantilever from a fixed root, the canopy bobs and bends
// against a wind vector. No frame here is another frame translated.
import { makeSprite, Anim } from '../core/gfx.js';

