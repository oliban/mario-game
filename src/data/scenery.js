// WATER_LINE — six frames. TWO crests, PINNED at x=4 and x=12, present in every
// single frame; only their HEIGHT animates. Each frame is composited from one crest
// kit stamped at those two fixed columns, so a crest physically cannot slide sideways
// — the previous version carried one crest per frame and jumped it half a tile, which
// is exactly what this construction makes impossible.
//
// The two heights run out of phase and rise slowly but collapse fast, so all six
// (h@4, h@12) pairs are distinct: (3,1) (4,2) (2,3) (1,3) (1,4) (2,2). A crest that
