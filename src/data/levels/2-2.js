// ---------------------------------------------------------------------------
// WORLD 2-2 — underwater, 176 tiles.
//
// The first water level. There is no air in the flooded section: the ceiling at
// row 0 caps it and the player swims the whole way, so the level is paced by
// vertical channels rather than by jumps.
//
// The channel alternates — coral rising from the sea floor at 22, 58, 96 and
// 130, stone hanging from the ceiling at 38, 74 and 112 — so the swim is a slow
// weave rather than a straight line. Every gap is at least four tiles, which is
// two body heights for big Mario, because a swimming stroke overshoots.
//
// Bloopers chase in the open water; the grey cheep-cheeps patrol across it.
// Neither can be stomped underwater, so the fire flower is the only answer and
// the level is otherwise about reading the current.
//
// The water stops at 147. The last 28 tiles are dry shore, so the flagpole is
// taken on foot exactly like any other level.
//
// Legend: . air  # ground/stone  _ water  ~ water surface  g coral
//         | ^ flagpole
// ---------------------------------------------------------------------------

