#!/usr/bin/env node
// Generate world 2's level modules from the original's own area data.
//   node tools/smb-gen-world2.mjs
//
// Everything positional here — widths, pipe columns, hole widths, the beanstalk
// brick, the jumpspring, the flagpole and castle — comes from reference/, not
// from anyone's memory of the game. Deviations are marked DEVIATION and are
// only where this engine lacks a mechanism the original had.

import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { emitLevel, bonusRoomSource, skyAreaSource } from './smb-build.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src', 'data', 'levels');


const SOLID = new Set(['#', 'B', '=', 'S', 'U']);

// Item blocks stay where the original put them. Three separate heuristics here
// used to relocate any block that sat more than a jump above its own ground,
// and all three were wrong, because the premise was wrong.
//
// 2-1 is the case that exposed it: the original stacks a Hidden1Up on SMB row 3
// over a hidden coin block on SMB row 7 in the SAME column, and 2-3's power-up
// at column 102 hangs over open water. Both are struck from a moving jump — off
// the used block in 2-1, off the bridge in 2-3 — which tools/playthrough.mjs's
// `bumpSpots` cannot model, since it only looks for footing within one column
// of the block. That is a limit of the checker, not a defect in the level, and
// distorting the original's geometry to satisfy it makes the levels less
// faithful without making them more playable.
//
// DEVIATION: the original lets a power-up slide out sideways from a block set
// into a ceiling; this engine emerges it upward and would bury it. One tile of
// air is carved above any capped item block. That one is a real engine limit.
function relieveBlocks(rows) {
  const CAPPED = new Set(['?', 'M']);
  const g = rows.map((r) => r.split(''));
  for (let y = 1; y < g.length; y++) {
    for (let x = 0; x < g[y].length; x++) {
      if (CAPPED.has(g[y][x]) && SOLID.has(g[y - 1][x])) g[y - 1][x] = '.';
    }
  }
  return g.map((r) => r.join(''));
}


// Spawn on the first column with two clear rows above solid ground, so the
// terrain decides where the player starts instead of a guessed constant.
function findSpawn(rows) {
  for (let x = 2; x < 30; x++) {
    for (let y = 12; y >= 3; y--) {
      const solid = '#B=SU'.includes(rows[y][x]);
      const clear = rows[y - 1][x] === '.' && rows[y - 2][x] === '.';
      if (solid && clear) return { x, y: y - 1 };
    }
  }
  return { x: 2, y: 12 };
}


// Podoboos are lava bubbles, and they leap out of the surface of the lava.
// ForegroundScenery now supplies that lava column by column, so they only need
// seating on it rather than pools dug for them.
function seatPodoboos(rows, ents) {
  const g = rows.map((r) => r.split(''));
  for (const e of ents) {
    if (e.type !== 'podoboo') continue;
    let top = g.length - 1;
    for (let y = 0; y < g.length; y++) {
      if (g[y][e.x] === 'L') { top = y; break; }
    }
    e.y = top;
  }
  return g.map((r) => r.join(''));
}


// A column with floor under it and two clear rows above, for a warp to land in.
function landingNear(rows, want) {
  for (let d = 0; d < 40; d++) {
    for (const x of [want + d, want - d]) {
      if (x < 2 || x >= rows[0].length) continue;
      if (SOLID.has(rows[13][x]) && rows[12][x] === '.' && rows[11][x] === '.') return x;
    }
  }
  return want;
}

const j = (v) => JSON.stringify(v);
const tilesBlock = (rows) => 'const TILES = [\n' + rows.map((r) => `  '${r}',\n`).join('') + '];\n';
const entsBlock = (ents) =>
  ents.map((e) => `    ${j(e).replace(/"([a-z]+)":/g, '$1: ').replace(/"/g, "'")},`).join('\n');

function header(id, note) {
  return `// ---------------------------------------------------------------------------
// WORLD ${id}
//
// Generated by tools/smb-gen-world2.mjs from the original's area data — see
// reference/smb-areas.json. Pipe columns, hole widths, block rows, the
// staircases, the flagpole and the castle are the original's own numbers, not
// an approximation of them. Re-run the generator rather than editing by hand.
//
${note}
// ---------------------------------------------------------------------------

`;
}

// ---------------------------------------------------------------------- 2-1
{
  const L = emitLevel('2-1', { theme: 'overworld' });
  const warp = L.meta.pipes.find((p) => p.warp);
  // Piranha plants are no longer guessed from the enemy stream: VerticalPipe
  // creates them itself, centred on the pipe, so smb-build emits them.
  const ents = L.entities.slice();
  const rows21 = relieveBlocks(L.rows);
  // HELD BACK, deliberately. The room's own record names column 115 for world 2
  // and a pipe does stand there — but GroundArea9's enemy stream puts a goomba at
  // column 116, right at that mouth, and coming up under it is fatal every time.
  // The original is safe there because ProcessEnemyData never spawns an enemy
  // already behind the screen's right edge on arrival (asm:7943-7957, and the
  // silent skip at CheckThreeBytes 8041-8054); our activation rule
  // (entity.js:397-403) has no such lower bound and wakes it. Switch this to
  // `bonusReturn(L.meta, 2, 0)` the day that rule is fixed — every other world
  // already takes the data.
  const out = { col: landingNear(rows21, 108), top: 12 };
  const backCol = landingNear(rows21, 128);
  const body = `
${bonusRoomSource('2-1b', 'WORLD 2-1', 0, out.col, out.top)}
${skyAreaSource('2-1c', 'WORLD 2-1', `{ area: 'main', x: ${backCol}.5, y: 12, exit: 'up' }`, 'GroundArea12')}
export default {
  id: '2-1',
  name: 'WORLD 2-1',
  time: 400,
  theme: 'overworld',
  music: 'overworld',
  width: ${L.width},
  height: 15,
  spawn: { x: 2, y: 12 },
  tiles: TILES,
  contents: [
${L.contents.map((c) => `    ${j(c).replace(/"([a-z]+)":/g, '$1: ').replace(/"/g, "'")},`).join('\n')}
    { x: 83, y: 5, item: 'vine', height: 11, warp: { to: { area: '2-1c', x: 3.5, y: 12, exit: 'none' } } },
  ],
  entities: [
${entsBlock(ents)}
  ],
  warps: [
    { from: { x: ${warp.x}, y: ${warp.top} }, dir: 'down', to: { area: '2-1b', x: 3.5, y: 12, exit: 'down' } },
  ],
  areas: { '2-1b': BONUS, '2-1c': SKY },
  flagpole: { x: ${L.meta.flagpole.x} },
  castle: { x: ${L.meta.castle.x} },
};
`;
  writeFileSync(
    join(OUT, '2-1.js'),
    header('2-1 — overworld', '// The beanstalk, the warp pipe and the jumpspring are all the original\'s.') +
      tilesBlock(rows21) +
      body
  );
}

// ---------------------------------------------------------------------- 2-2
{
  const L = emitLevel('2-2', { theme: 'water' });
  const rows = L.rows;
  // The original's WaterPipe IS the exit: the area's last AlterAreaAttributes
  // raises terrain 15, solid top to bottom, and the pipe is the one gap in that
  // wall. Swimming into it is how you leave, rather than scraping over the wall
  // along the water surface.
  //
  // The trigger column is the WATER in front of the mouth, not the mouth tile
  // itself. The pipe metatiles are solid ($6b and $6c both clear the block
  // buffer's bar), so a swimmer collides with the mouth and stops with his
  // leading edge exactly on the boundary of the engine's 2px entry window — it
  // does fire there, but only just. Anchoring one column left gives the whole
  // tile as the window.
  const wp = L.meta.waterPipe;
  const body = `
export default {
  id: '2-2',
  name: 'WORLD 2-2',
  time: 400,
  theme: 'water',
  music: 'underwater',
  width: ${L.width},
  height: 15,
  spawn: { x: 2, y: 6 },
  tiles: TILES,
  entities: [
${entsBlock(L.entities)}
  ],
  warps: [
    { from: { x: ${wp.x - 1}, y: ${wp.top} }, dir: 'right', to: { complete: true } },
  ],
  flagpole: null,
  castle: null,
};
`;
  writeFileSync(
    join(OUT, '2-2.js'),
    header(
      '2-2 — underwater',
      "// This area ends the way the original ends it: at the WaterPipe in column " +
        wp.x +
        ',\n' +
        '// cut into the solid wall the last AlterAreaAttributes raises. Swimming into\n' +
        '// it finishes the level — tally and all — so there is no flagpole here, and\n' +
        '// the original has none either. Every column is the original\'s.'
    ) +
      tilesBlock(relieveBlocks(rows)) +
      body
  );
}

// ---------------------------------------------------------------------- 2-3
{
  const L = emitLevel('2-3', { theme: 'overworld' });
  // The leaping cheep-cheeps are the original's own Frenzy objects at columns
  // 26 and 137, with the stop at 197, emitted as `frenzy` entities. They used
  // to be a row of hand-placed cheeps because this engine had no spawner.
  const ents = L.entities.slice();
  const body = `
export default {
  id: '2-3',
  name: 'WORLD 2-3',
  time: 400,
  theme: 'overworld',
  music: 'overworld',
  width: ${L.width},
  height: 15,
  spawn: { x: 2, y: 11 },
  tiles: TILES,
  entities: [
${entsBlock(ents)}
  ],
  flagpole: { x: ${L.meta.flagpole.x} },
  castle: { x: ${L.meta.castle.x} },
};
`;
  writeFileSync(
    join(OUT, '2-3.js'),
    header(
      '2-3 — the bridges',
      "// The leaping cheep-cheeps come from the original's own Frenzy objects at\n// columns 26 and 137, with the stop frenzy at 197. Almost every hand-placed\n// enemy in this area is flagged hard-mode-only and so is absent on a first\n// quest, exactly as in the original."
    ) +
      tilesBlock(relieveBlocks(L.rows)) +
      body
  );
}

// ---------------------------------------------------------------------- 2-4
{
  const L = emitLevel('2-4', { theme: 'castle' });
  const ents = L.entities.slice();
  const T24 = seatPodoboos(relieveBlocks(L.rows), ents);
  const SP24 = findSpawn(T24);
  const body = `
export default {
  id: '2-4',
  name: 'WORLD 2-4',
  time: 300,
  theme: 'castle',
  music: 'castle',
  width: ${L.width},
  height: 15,
  spawn: { x: ${SP24.x}, y: ${SP24.y} },
  tiles: TILES,
  entities: [
${entsBlock(ents)}
  ],
  flagpole: null,
  castle: { x: ${L.width - 6}, tall: true },
};
`;
  writeFileSync(
    join(OUT, '2-4.js'),
    header('2-4 — castle', "// Bowser at 135, the bridge at 128 and the axe at 141 are the original's.") +
      tilesBlock(T24) +
      body
  );
}

console.log('regenerated 2-1, 2-2, 2-3, 2-4 from reference data');
