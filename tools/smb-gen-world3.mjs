#!/usr/bin/env node
// Generate world 3's level modules from the original's own area data.
//   node tools/smb-gen-world3.mjs
//
// Same rules as the world-1 and world-2 generators: every position comes from
// reference/, not from anyone's memory of the game, and deviations are marked
// DEVIATION and exist only where this engine lacks a mechanism the original had.
//
// NIGHT. 3-1, 3-2 and 3-3 are night levels, and the mechanism is a palette
// index rather than a level type. BackgroundColors is indexed by AreaType when
// BackgroundColorCtrl is zero and by the control itself when it is 4 or more:
//
//   .db $22, $22, $0f, $0f   ; by area type   (water, ground, underground, castle)
//   .db $0f, $22, $0f, $0f   ; by colour ctrl (4, 5, 6, 7)
//
// $22 is the day blue and $0f is black. 3-1 sets control 6 from an
// AlterAreaAttributes at column 6, 3-2 sets 6 from its header and 3-3 sets 4,
// so all three land on $0f. They are emitted as `sky: 'night'` over an ordinary
// overworld theme, so every tile, prop and animation still resolves through the
// existing theme tables.

import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { emitLevel, bonusRoomSource, skyAreaSource, bonusReturn } from './smb-build.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src', 'data', 'levels');

const SOLID = new Set(['#', 'B', '=', 'S', 'U']);

// DEVIATION: the original lets a power-up slide out sideways from a block set
// into a ceiling; this engine emerges it upward and would bury it. One tile of
// air is carved above any capped item block. Item blocks are otherwise left
// exactly where the original puts them.
function relieveBlocks(rows) {
  const CAPPED = new Set(['?', 'M']);
  const g = rows.map((r) => r.split(''));
  for (let y = 1; y < g.length; y++) {
    for (let x = 0; x < g[y].length; x++) {
      if (CAPPED.has(g[y][x]) && SOLID.has(g[y - 1][x])) g[y - 1][x] = '.';
    }
  }
  return g.map((r) => r.join(''));
}

// Spawn on the first column with two clear rows above solid ground, scanning
// from row 13 — the standard floor — upward.
function findSpawn(rows) {
  for (let x = 2; x < 30; x++) {
    for (let y = 13; y >= 3; y--) {
      const solid = SOLID.has(rows[y][x]);
      const clear = rows[y - 1][x] === '.' && rows[y - 2][x] === '.';
      if (solid && clear) return { x, y: y - 1 };
    }
  }
  return { x: 2, y: 12 };
}

// Podoboos leap out of the surface of the lava, so seat them on it.
function seatPodoboos(rows, ents) {
  const g = rows.map((r) => r.split(''));
  for (const e of ents) {
    if (e.type !== 'podoboo') continue;
    let top = g.length - 1;
    for (let y = 0; y < g.length; y++) {
      if (g[y][e.x] === 'L') { top = y; break; }
    }
    e.y = top;
  }
  return g.map((r) => r.join(''));
}

// A column with floor under it and two clear rows above, for a warp to land in.
function landingNear(rows, want) {
  for (let d = 0; d < 40; d++) {
    for (const x of [want + d, want - d]) {
      if (x < 2 || x >= rows[0].length) continue;
      if (SOLID.has(rows[13][x]) && rows[12][x] === '.' && rows[11][x] === '.') return x;
    }
  }
  return want;
}

const j = (v) => JSON.stringify(v);
const tilesBlock = (rows) => 'const TILES = [\n' + rows.map((r) => `  '${r}',\n`).join('') + '];\n';
const entsBlock = (ents) =>
  ents.map((e) => `    ${j(e).replace(/"([a-zA-Z]+)":/g, '$1: ').replace(/"/g, "'")},`).join('\n');
const contentsBlock = (cs) =>
  cs.map((c) => `    ${j(c).replace(/"([a-zA-Z]+)":/g, '$1: ').replace(/"/g, "'")},`).join('\n');

function header(id, note) {
  return `// ---------------------------------------------------------------------------
// WORLD ${id}
//
// Generated by tools/smb-gen-world3.mjs from the original's area data — see
// reference/smb-areas.json. Pipe columns and heights, hole widths, block rows,
// the staircases, the flagpole and the castle are the original's own numbers,
// not an approximation of them. Re-run the generator rather than editing by
// hand.
//
${note}
// ---------------------------------------------------------------------------

`;
}

// ---------------------------------------------------------------------- 3-1
{
  const L = emitLevel('3-1', { theme: 'overworld' });
  const rows = relieveBlocks(L.rows);
  const sp = findSpawn(rows);
  const vine = L.meta.vine;
  const back = landingNear(rows, 160);
  const wp = L.meta.warpPipe;
  const out = bonusReturn(L.meta, 3, 4) || { col: landingNear(rows, 100), top: 12 };
  const body = `
${bonusRoomSource('3-1b', 'WORLD 3-1', 4, out.col, out.top)}
${skyAreaSource('3-1c', 'WORLD 3-1', `{ area: 'main', x: ${back}.5, y: 12, exit: 'up' }`, 'GroundArea21')}
export default {
  id: '3-1',
  name: 'WORLD 3-1',
  time: 400,
  theme: 'overworld',
  sky: 'night',
  scenery: 'snow',
  music: 'overworld',
  width: ${L.width},
  height: 15,
  spawn: { x: ${sp.x}, y: ${sp.y} },
  tiles: TILES,
  contents: [
${contentsBlock(L.contents)}
    { x: ${vine.x}, y: ${vine.y}, item: 'vine', height: 11, warp: { to: { area: '3-1c', x: 3.5, y: 12, exit: 'none' } } },
  ],
  entities: [
${entsBlock(L.entities)}
  ],
  warps: [
    { from: { x: ${wp.x}, y: ${wp.top} }, dir: 'down', to: { area: '3-1b', x: 2.5, y: 3, exit: 'down' } },
  ],
  areas: { '3-1b': BONUS, '3-1c': SKY },
  flagpole: { x: ${L.meta.flagpole.x} },
  castle: { x: ${L.meta.castle.x} },
};
`;
  writeFileSync(
    join(OUT, '3-1.js'),
    header(
      '3-1 — overworld, night',
      '// Night from column 6, where an AlterAreaAttributes with d6 set and a value of\n' +
        '// 6 raises BackgroundColorCtrl. The first six columns are still blue in the\n' +
        '// original; we take the whole level as night, which is the only deviation in\n' +
        '// the sky.\n' +
        '//\n' +
        "// The beanstalk brick at " + vine.x + ", the jumpspring at " +
        (L.meta.springs[0] ? L.meta.springs[0].x : '-') +
        ", the bridge over the water\n" +
        '// at 77 and both drowning pools are the original\'s.\n' +
        '//\n' +
        '// The pipe at column ' + L.meta.warpPipe.x + ' is flagged in the data as one that leads somewhere,\n' +
        "// and drops into a coin room built to 1-1's shape."
    ) +
      tilesBlock(rows) +
      body
  );
}

// ---------------------------------------------------------------------- 3-2
{
  const L = emitLevel('3-2', { theme: 'overworld' });
  const rows = relieveBlocks(L.rows);
  const sp = findSpawn(rows);
  const body = `
export default {
  id: '3-2',
  name: 'WORLD 3-2',
  time: 400,
  theme: 'overworld',
  sky: 'night',
  scenery: 'snow',
  music: 'overworld',
  width: ${L.width},
  height: 15,
  spawn: { x: ${sp.x}, y: ${sp.y} },
  tiles: TILES,
  contents: [
${contentsBlock(L.contents)}
  ],
  entities: [
${entsBlock(L.entities)}
  ],
  flagpole: { x: ${L.meta.flagpole.x} },
  castle: { x: ${L.meta.castle.x} },
};
`;
  writeFileSync(
    join(OUT, '3-2.js'),
    header(
      '3-2 — overworld, night',
      '// Night from the header: byte 0 is $96, and its low three bits are 6, which is\n' +
        '// 4 or more and so sets BackgroundColorCtrl rather than ForegroundScenery.\n' +
        '//\n' +
        '// A sparse level by design — the original gives it five solid columns, three\n' +
        '// holes, one pipe and a staircase, and leans on its koopa groups instead.'
    ) +
      tilesBlock(rows) +
      body
  );
}

// ---------------------------------------------------------------------- 3-3
{
  const L = emitLevel('3-3', { theme: 'overworld' });
  const rows = relieveBlocks(L.rows);
  const sp = findSpawn(rows);
  const body = `
export default {
  id: '3-3',
  name: 'WORLD 3-3',
  time: 300,
  theme: 'athletic',
  sky: 'night',
  music: 'overworld',
  width: ${L.width},
  height: 15,
  spawn: { x: ${sp.x}, y: ${sp.y} },
  tiles: TILES,
  contents: [
${contentsBlock(L.contents)}
  ],
  entities: [
${entsBlock(L.entities)}
  ],
  flagpole: { x: ${L.meta.flagpole.x} },
  castle: { x: ${L.meta.castle.x} },
};
`;
  writeFileSync(
    join(OUT, '3-3.js'),
    header(
      '3-3 — the lifts, night',
      '// The lift level. The original uses three of our four platform modes and no\n' +
        '// vertical lifts at all: seven horizontal ($28), one that falls away under you\n' +
        '// ($29 at column 60), and two BALANCE PAIRS ($24 at 81 with 88, and at 136\n' +
        '// with 140).\n' +
        '//\n' +
        '// A balance pair is one rope with a platform on each end. The original writes\n' +
        '// both halves into the enemy stream and links them by adjacency through\n' +
        '// BalPlatformAlignment; our Platform spawns its own partner in pulley mode, so\n' +
        '// only the first half is emitted, and the rope span and balance point are\n' +
        "// taken from where the original put the second.\n" +
        '//\n' +
        '// Terrain is 0 from column 15: no floor at all, so everything you stand on is\n' +
        '// an AreaStyleObject tree ledge or a lift.'
    ) +
      tilesBlock(rows) +
      body
  );
}

// ---------------------------------------------------------------------- 3-4
{
  const L = emitLevel('3-4', { theme: 'castle' });
  const ents = L.entities.slice();
  const rows = seatPodoboos(relieveBlocks(L.rows), ents);
  const sp = findSpawn(rows);
  const body = `
export default {
  id: '3-4',
  name: 'WORLD 3-4',
  time: 300,
  theme: 'castle',
  music: 'castle',
  width: ${L.width},
  height: 15,
  spawn: { x: ${sp.x}, y: ${sp.y} },
  tiles: TILES,
  contents: [
${contentsBlock(L.contents)}
  ],
  entities: [
${entsBlock(ents)}
  ],
  flagpole: null,
  castle: { x: ${L.width - 6}, tall: true },
};
`;
  writeFileSync(
    join(OUT, '3-4.js'),
    header(
      '3-4 — castle',
      "// Bowser at 135 and the axe at 141 are the original's. Twenty-four\n" +
        '// AlterAreaAttributes drive the ceiling and floor up and down the whole way —\n' +
        '// this is the castle that keeps changing shape under you.'
    ) +
      tilesBlock(rows) +
      body
  );
}

console.log('regenerated 3-1, 3-2, 3-3, 3-4 from reference data');
