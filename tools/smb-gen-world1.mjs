#!/usr/bin/env node
// Generate world 1's level modules from the original's own area data.
//   node tools/smb-gen-world1.mjs
//
// Same rules as smb-gen-world2.mjs: every position here comes from reference/,
// not from anyone's memory of the game, and deviations are marked DEVIATION and
// exist only where this engine lacks a mechanism the original had.
//
// Two things in 1-1 are OURS and are preserved verbatim across regeneration:
//   * the '1-1w' warp zone on the first pipe, built from roster.js so it always
//     lists every level that exists — it is the playtest shortcut;
//   * the '1-1b' coin room, which the original's own warp pipe at column 57
//     leads to.

import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { emitLevel, bonusRoomSource } from './smb-build.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src', 'data', 'levels');

const SOLID = new Set(['#', 'B', '=', 'S', 'U']);

// DEVIATION: the original lets a power-up slide out sideways from a block set
// into a ceiling; this engine emerges it upward and would bury it. One tile of
// air is carved above any capped item block. Item blocks are otherwise left
// exactly where the original puts them — see the note in smb-gen-world2.mjs.
function relieveBlocks(rows) {
  const CAPPED = new Set(['?', 'M']);
  const g = rows.map((r) => r.split(''));
  for (let y = 1; y < g.length; y++) {
    for (let x = 0; x < g[y].length; x++) {
      if (CAPPED.has(g[y][x]) && SOLID.has(g[y - 1][x])) g[y - 1][x] = '.';
    }
  }
  return g.map((r) => r.join(''));
}

// Spawn on the first column with two clear rows above solid ground. The scan
// starts at row 13, the standard floor: starting at 12 (as world 2's copy did)
// misses it entirely and lands the player deep inside the level.
function findSpawn(rows) {
  for (let x = 2; x < 30; x++) {
    for (let y = 13; y >= 3; y--) {
      const solid = SOLID.has(rows[y][x]);
      const clear = rows[y - 1][x] === '.' && rows[y - 2][x] === '.';
      if (solid && clear) return { x, y: y - 1 };
    }
  }
  return { x: 2, y: 12 };
}

// Podoboos leap out of the surface of the lava, so seat them on it.
function seatPodoboos(rows, ents) {
  const g = rows.map((r) => r.split(''));
  for (const e of ents) {
    if (e.type !== 'podoboo') continue;
    let top = g.length - 1;
    for (let y = 0; y < g.length; y++) {
      if (g[y][e.x] === 'L') { top = y; break; }
    }
    e.y = top;
  }
  return g.map((r) => r.join(''));
}

const j = (v) => JSON.stringify(v);
const tilesBlock = (rows) => 'const TILES = [\n' + rows.map((r) => `  '${r}',\n`).join('') + '];\n';
const entsBlock = (ents) =>
  ents.map((e) => `    ${j(e).replace(/"([a-z]+)":/g, '$1: ').replace(/"/g, "'")},`).join('\n');
const contentsBlock = (cs) =>
  cs.map((c) => `    ${j(c).replace(/"([a-z]+)":/g, '$1: ').replace(/"/g, "'")},`).join('\n');

function header(id, note) {
  return `// ---------------------------------------------------------------------------
// WORLD ${id}
//
// Generated by tools/smb-gen-world1.mjs from the original's area data — see
// reference/smb-areas.json. Pipe columns and heights, hole widths, block rows,
// the staircases, the flagpole and the castle are the original's own numbers,
// not an approximation of them. Re-run the generator rather than editing by
// hand.
//
${note}
// ---------------------------------------------------------------------------

`;
}

// ---------------------------------------------------------------------- 1-1
{
  const L = emitLevel('1-1', { theme: 'overworld' });
  const warp = L.meta.pipes.find((p) => p.warp);
  const first = L.meta.pipes[0];
  // The coin room's side pipe puts you back into the main area. The original's
  // own re-entry point is the pipe at column 163, the one after the staircases,
  // which is exactly why taking the room is a shortcut rather than a detour.
  const backPipe = L.meta.pipes.find((p) => p.x > 100 && !p.warp);

  const body = `
${bonusRoomSource('1-1b', 'WORLD 1-1', 0, backPipe.x, backPipe.top)}
// The warp zone, reached by the first pipe at col ${first.x}. SMB hides its warp zones
// behind a ceiling run or a vine; this one is deliberately on the very first
// pipe, because its job is to get a tester into any level in two seconds.
//
// It is BUILT from the roster rather than written out, so every level that
// exists has a pipe here and a new world needs no edit to this file. Each pipe
// is a two-tile stub on the floor at row 11 and the label above it is a \`signs\`
// entry — level text painted into world space, the way SMB writes its world
// numbers onto the warp-zone backdrop.
const WZ_FIRST = 5; // column of the first pipe
const WZ_STEP = 4; // columns between pipe left edges

function buildWarpZone(order) {
  const width = WZ_FIRST + order.length * WZ_STEP + 2;
  const pipeCols = order.map((_, i) => WZ_FIRST + i * WZ_STEP);
  const blank = (fill) => fill.repeat(width);
  const room = (mid) => '#' + mid + '#';
  const open = () => room('.'.repeat(width - 2));

  const pipeRow = (left, right) => {
    const row = '.'.repeat(width).split('');
    for (const c of pipeCols) {
      row[c] = left;
      row[c + 1] = right;
    }
    row[0] = '#';
    row[width - 1] = '#';
    return row.join('');
  };

  const tiles = [
    blank('#'),
    blank('#'),
    '##[]' + '#'.repeat(width - 4),
    '#.{}' + '.'.repeat(width - 5) + '#',
    open(),
    open(),
    open(),
    open(),
    open(),
    open(),
    open(),
    pipeRow('[', ']'),
    pipeRow('{', '}'),
    blank('#'),
    blank('#'),
  ];

  const title = 'WARP ZONE';
  const signs = [{ x: (width - title.length) / 2, y: 5, text: title }];
  for (let i = 0; i < order.length; i++) {
    // Centre the three-glyph label on the two-tile pipe: 24px of text over 32px
    // of pipe leaves 4px, which is a quarter of a tile.
    signs.push({ x: pipeCols[i] + 0.25, y: 9, text: order[i] });
  }

  return {
    id: '1-1w',
    name: 'WARP ZONE',
    theme: 'underground',
    music: 'underground',
    width,
    height: 15,
    spawn: { x: 2, y: 10 },
    tiles,
    entities: [],
    signs,
    warps: order.map((id, i) => ({
      from: { x: pipeCols[i], y: 11 },
      dir: 'down',
      to: { level: id },
    })),
  };
}

const WARP = buildWarpZone(ORDER);

export default {
  id: '1-1',
  name: 'WORLD 1-1',
  time: 400,
  theme: 'overworld',
  music: 'overworld',
  width: ${L.width},
  height: 15,
  spawn: { x: 2, y: 12 },
  tiles: TILES,
  contents: [
${contentsBlock(L.contents)}
  ],
  entities: [
${entsBlock(L.entities)}
  ],
  warps: [
    { from: { x: ${warp.x}, y: ${warp.top} }, dir: 'down', to: { area: '1-1b', x: 2.5, y: 3, exit: 'down' } },
    // The first pipe in the game is the tester's door into every other level.
    { from: { x: ${first.x}, y: ${first.top} }, dir: 'down', to: { area: '1-1w', x: 2.5, y: 3, exit: 'down' } },
  ],
  areas: { '1-1b': BONUS, '1-1w': WARP },
  flagpole: { x: ${L.meta.flagpole.x} },
  castle: { x: ${L.meta.castle.x + 1} },
};
`;
  writeFileSync(
    join(OUT, '1-1.js'),
    header(
      '1-1 — overworld',
      "// The hand-authored version of this level had two pipes that do not exist in\n" +
        '// the original (columns 110 and 122), was missing the one at 179, had the pipe\n' +
        '// at 163 a row too high, put the star in the wrong brick, and gave 1-1 piranha\n' +
        "// plants — which it has none of: VerticalPipe's plant is skipped when\n" +
        '// AreaNumber and WorldNumber are both zero, and 1-1 is the only level that is.\n' +
        '//\n' +
        "// The castle column is the original's 202 + 1: our castle base is cut open so\n" +
        '// the walk-off can reach the door, and the sprite is drawn one tile right.'
    ) +
      "import { ORDER } from './roster.js';\n\n" +
      tilesBlock(relieveBlocks(L.rows)) +
      body
  );
}

// ---------------------------------------------------------------------- 1-2
